func initSubcommands() -> [String: SubCommandParser] {
    var result: [String: SubCommandParser] = [:]
    for kind in CmdKind.allCases {
        result[kind.rawValue] = switch kind {
            case .balanceSizes: SubCommandParser(BalanceSizesCmdArgs.init)
            case .close: SubCommandParser(CloseCmdArgs.init)
            case .closeAllWindowsButCurrent: SubCommandParser(CloseAllWindowsButCurrentCmdArgs.init)
            case .config: SubCommandParser(parseConfigCmdArgs)
            case .debugWindows: SubCommandParser(DebugWindowsCmdArgs.init)
            case .echo: SubCommandParser(EchoCmdArgs.init)
            case .enable: SubCommandParser(parseEnableCmdArgs)
            case .eval: SubCommandParser(EvalCmdArgs.init)
            case .execAndForget: nil // exec-and-forget is parsed separately
            case ._false: SubCommandParser(FalseCmdArgs.init)
            case .flattenWorkspaceTree: SubCommandParser(FlattenWorkspaceTreeCmdArgs.init)
            case .focus: SubCommandParser(parseFocusCmdArgs)
            case .focusBackAndForth: SubCommandParser(FocusBackAndForthCmdArgs.init)
            case .focusMonitor: SubCommandParser(parseFocusMonitorCmdArgs)
            case .fullscreen: SubCommandParser(parseFullscreenCmdArgs)
            case .joinWith: SubCommandParser(JoinWithCmdArgs.init)
            case .layout: SubCommandParser(parseLayoutCmdArgs)
            case .listApps: SubCommandParser(parseListAppsCmdArgs)
            case .listExecEnvVars: SubCommandParser(ListExecEnvVarsCmdArgs.init)
            case .listModes: SubCommandParser(ListModesCmdArgs.init)
            case .listMonitors: SubCommandParser(parseListMonitorsCmdArgs)
            case .listWindows: SubCommandParser(parseListWindowsCmdArgs)
            case .listWorkspaces: SubCommandParser(parseListWorkspacesCmdArgs)
            case .macosNativeFullscreen: SubCommandParser(parseMacosNativeFullscreenCmdArgs)
            case .macosNativeMinimize: SubCommandParser(MacosNativeMinimizeCmdArgs.init)
            case .mode: SubCommandParser(ModeCmdArgs.init)
            case .move: SubCommandParser(MoveCmdArgs.init)
            case .moveMouse: SubCommandParser(parseMoveMouseCmdArgs)
            case .moveNodeToMonitor: SubCommandParser(parseMoveNodeToMonitorCmdArgs)
            case .moveNodeToWorkspace: SubCommandParser(parseMoveNodeToWorkspaceCmdArgs)
            case .moveWorkspaceToMonitor: SubCommandParser(parseMoveWorkspaceToMonitorCmdArgs)
            case .reloadConfig: SubCommandParser(ReloadConfigCmdArgs.init)
            case .resize: SubCommandParser(ResizeCmdArgs.init)
            case .runCallback: SubCommandParser(parseRunCallbackCmdArgs)
            case .split: SubCommandParser(SplitCmdArgs.init)
            case .subscribe: SubCommandParser(parseSubscribeCmdArgs)
            case .summonWorkspace: SubCommandParser(SummonWorkspaceCmdArgs.init)
            case .swap: SubCommandParser(SwapCmdArgs.init)
            case .test: SubCommandParser(TestCmdArgs.init)
            case .testNot: SubCommandParser(parseTestNotCmdArgs)
            case .triggerBinding: SubCommandParser(parseTriggerBindingCmdArgs)
            case ._true: SubCommandParser(TrueCmdArgs.init)
            case .volume: SubCommandParser(VolumeCmdArgs.init)
            case .workspace: SubCommandParser(parseWorkspaceCmdArgs)
            case .workspaceBackAndForth: SubCommandParser(WorkspaceBackAndForthCmdArgs.init)
        }
    }
    // Deprecated aliases
    result["move-through"] = SubCommandParser(MoveCmdArgs.init)
    result["move-workspace-to-display"] = SubCommandParser(parseMoveWorkspaceToMonitorCmdArgs)
    return result
}
