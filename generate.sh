#!/usr/bin/env bash
cd "$(dirname "$0")"
source ./script/setup.sh

export XCODEGEN_AEROSPACE_CODE_SIGN_IDENTITY="aerospace-codesign-certificate"
build_version="0.0.0-SNAPSHOT"
generate_xcodeproj=1
generate_cmd_help=1
generate_git_hash=0
while test $# -gt 0; do
    case $1 in
        --build-version) build_version="$2"; shift 2 ;;
        --codesign-identity) XCODEGEN_AEROSPACE_CODE_SIGN_IDENTITY="$2"; shift 2 ;;
        --generate-git-hash) generate_git_hash=1; shift 1;;
        --ignore-cmd-help) generate_cmd_help=0; shift 1 ;;
        --ignore-xcodeproj) generate_xcodeproj=0; shift 1 ;;
        *) echo "Unknown option $1"; exit 1 ;;
    esac
done

export XCODEGEN_SWIFT_LANGUAGE_VERSION=6.2
# All generated files are written with write-if-changed, which keeps the mtime of unchanged files, so `swift build` can stay a no-op
sed "1s|.*|// swift-tools-version: ${XCODEGEN_SWIFT_LANGUAGE_VERSION}|" Package.swift | write-if-changed Package.swift

if test $generate_cmd_help = 1; then
    # It takes 300ms for the script to complete
    ./script/generate-cmd-help.sh
fi

write-if-changed Sources/Common/versionGenerated.swift <<EOF
// FILE IS GENERATED BY generate.sh
public let aeroSpaceAppVersion = "$build_version"
EOF

entries() {
    # Bash string ops instead of basename/grep/sed pipes: build-debug.sh runs this every time, and the processes add up
    for file in docs/aerospace-*.adoc; do
        if [[ $file == *exec-and-forget* ]]; then
            continue
        fi
        subcommand="${file#docs/aerospace-}"
        subcommand="${subcommand%.adoc}"
        desc="$(sed -n -E '/:manpurpose:/ { s/:manpurpose: //; p; }' "$file")"
        echo "    [\"  $subcommand\", \"$desc\"],"
    done
}

write-if-changed ./Sources/Cli/subcommandDescriptionsGenerated.swift <<EOF
// FILE IS GENERATED FROM docs/aerospace-*.adoc files
// TO REGENERATE THE FILE RUN generate.sh

let subcommandDescriptions = [
$(entries)
]
EOF

write-if-changed ./Sources/Common/gitHashGenerated.swift <<EOF
// FILE IS GENERATED BY generate.sh
public let gitHash = "$(if test $generate_git_hash = 0; then echo "SNAPSHOT"; else git rev-parse HEAD; fi)"
public let gitShortHash = "$(if test $generate_git_hash = 0; then echo "SNAPSHOT"; else git rev-parse --short HEAD; fi)"
EOF

if test $generate_xcodeproj = 1; then
    export XCODEGEN_AEROSPACE_VERSION=$build_version
    ./script/install-dep.sh --xcodegen
    cd xcode

    # Use the same Swift toolchain in xcodebuild
    XCODEGEN_TOOLCHAINS="$(plutil -extract CFBundleIdentifier raw "$(swiftly use --print-location)/Info.plist")"
    export XCODEGEN_TOOLCHAINS
    ../.deps/xcodegen/xcodegen # https://github.com/yonaskolb/XcodeGen
fi
